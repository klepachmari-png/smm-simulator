  function collected(day){
    var out=[], course=api.course();
    for(var i=0;i<Math.min(day,course.length);i++){
      var d=course[i];
      out.push('--- ДЕНЬ '+(i+1)+' · '+d.title+' ---');
      (d.fields||[]).forEach(function(f){
        var x=get(api.key(i+1,f[0])).trim();
        out.push(f[1]+': '+(x||'[НЕ ЗАПОВНЕНО]'));
      });
      var ch=get(api.key(i+1,'challenge')).trim();
      if(ch) out.push('Додаткове рішення користувача: '+ch);
      var accepted=get(api.key(i+1,'ai_accepted')).trim();
      if(accepted) out.push('Перевірена користувачем AI-версія: '+accepted);
      out.push('');
    }
    return out.join('\n');
  }

