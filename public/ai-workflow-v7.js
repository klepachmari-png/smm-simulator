function userInputs(day){
  var out=[];
  for(var i=0;i<Math.min(day,course().length);i++){
    var d=course()[i],rows=[];
    (d.fields||[]).forEach(function(f){
      var val=get(api.key(i+1,f[0])).trim();
      if(val) rows.push('- '+f[1]+': '+val);
    });
    if(rows.length){
      out.push('ДЕНЬ '+(i+1)+' · '+(route()==='B'?'ФАКТИ, ЯКІ ВВІВ ВЛАСНИК':'РОБОЧІ ВІДПОВІДІ УЧАСНИКА'));
      out=out.concat(rows);out.push('');
    }
  }
  return out.length?out.join('\n'):'[РОБОЧІ ПОЛЯ ЩЕ НЕ ЗАПОВНЕНІ]';
}
