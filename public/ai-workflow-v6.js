function caseFacts(day){
  var t=route(), out=[];
  if(t==='B') return '';
  if(t==='A') out.push('БАЗОВИЙ ФАКТ КЕЙСУ: SENSE BEAUTY — вигаданий салон у Варшаві.');
  if(t==='C') out.push('БАЗОВИЙ ФАКТ КЕЙСУ: це вигаданий навчальний клієнтський кейс для чинного SMM-спеціаліста.');
  for(var i=0;i<Math.min(day,course().length);i++){
    var d=course()[i];
    if(d&&d.scene) out.push('ДЕНЬ '+(i+1)+' · ФАКТИ СИТУАЦІЇ: '+d.scene);
  }
  return out.join('\n');
}
function userInputs(day){
  var out=[];
  for(var i=0;i<Math.min(day,course().length);i++){
    var d=course()[i], rows=[];
    (d.fields||[]).forEach(function(f){
      var val=get(api.key(i+1,f[0])).trim();
      if(val) rows.push('- '+f[1]+': '+val);
    });
    if(rows.length){
      out.push('ДЕНЬ '+(i+1)+' · ВЛАСНІ ВІДПОВІДІ УЧАСНИКА');
      out=out.concat(rows); out.push('');
    }
  }
  return out.length?out.join('\n'):'[КОРИСТУВАЧ ЩЕ НЕ ЗАПОВНИВ РОБОЧІ ПОЛЯ]';
}
